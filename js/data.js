const SYL = ['咕', '嚕', '嗶', '哩', '噠', '呣', '咪', '嘰', '塔', '薩', '囉', '哇', '啾', '咚', '嘎', '吥'];
export function gibberish(seed, len = 22) {
  let h = 0;
  for (const ch of String(seed)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  let out = '';
  for (let i = 0; i < len; i++) {
    h = (h * 1103515245 + 12345) >>> 0;
    out += SYL[(h >>> 16) % SYL.length];
    if (i % 5 === 4 && i < len - 1) out += ((h >>> 20) & 1) ? '，' : '　';
  }
  return out + '。';
}
